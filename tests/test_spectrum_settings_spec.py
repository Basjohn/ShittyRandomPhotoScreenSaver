"""Spectrum spec preserves its existing source projection and private runtime aliases."""
from __future__ import annotations

from types import SimpleNamespace

import pytest

from core.settings.default_contract import require_canonical_default
from core.settings.models import SpotifyVisualizerSettings
from core.settings.visualizer_mode_settings import control_runtime_attr, require_mode_settings


@pytest.mark.parametrize("values, mode, unique", [
    ({"spectrum_single_piece": False, "spectrum_rainbow_per_bar": False}, "segment", False),
    ({"spectrum_render_mode": "bars", "spectrum_single_piece": False,
      "spectrum_unique_colors": True, "spectrum_rainbow_per_bar": False, "rainbow_per_bar": False}, "bars", True),
    ({"spectrum_single_piece": True, "rainbow_per_bar": False}, "bars", False),
])
def test_spectrum_declared_input_migrations_apply_each_private_alias_once(values, mode, unique):
    from widgets.spotify_visualizer.config_applier import apply_logical_vis_mode_kwargs, apply_presentation_vis_mode_kwargs

    class Owner:
        def __init__(self):
            object.__setattr__(self, "writes", {})

        def __setattr__(self, key, value):
            self.writes[key] = self.writes.get(key, 0) + 1
            object.__setattr__(self, key, value)

    model = SpotifyVisualizerSettings.from_mapping(values, apply_preset_overlay=False)
    assert model.spectrum_render_mode == mode
    assert model.spectrum_unique_colors is unique
    serialized = model.to_dict()
    assert serialized["widgets.spotify_visualizer.spectrum_render_mode"] == mode
    assert serialized["widgets.spotify_visualizer.spectrum_unique_colors"] is unique
    logical, presentation = Owner(), Owner()
    apply_logical_vis_mode_kwargs(logical, values)
    apply_presentation_vis_mode_kwargs(presentation, values)
    assert logical.writes == {"_spectrum_single_piece": 1}
    assert presentation.writes == {"_rainbow_per_bar": 1}
    assert logical._spectrum_single_piece is (mode == "bars")
    assert presentation._rainbow_per_bar is unique
    assert not hasattr(logical, "_spectrum_render_mode")
    assert not hasattr(presentation, "_spectrum_unique_colors")


def test_spectrum_specs_reach_real_source_logical_presentation_and_capture_parameters_once():
    from widgets.spotify_visualizer.config_applier import (
        _populate_shared_visualizer_extras, apply_logical_vis_mode_kwargs, apply_presentation_vis_mode_kwargs,
    )
    from widgets.spotify_visualizer.logical_frame_capture import _common_style
    from widgets.spotify_visualizer.presentation_state import VisualizerPresentationState
    from widgets.spotify_visualizer.source_config_applier import apply_engine_vis_mode_kwargs, resolve_mode_source_config

    class CountWrites:
        def __setattr__(self, key, value):
            self.writes[key] = self.writes.get(key, 0) + 1
            object.__setattr__(self, key, value)

    class Logical(CountWrites):
        def __init__(self):
            object.__setattr__(self, "writes", {})

    class Presentation(CountWrites, VisualizerPresentationState):
        def __init__(self):
            object.__setattr__(self, "writes", {})
            super().__init__(SimpleNamespace(mode_id="spectrum"))

    defaults = require_canonical_default("widgets.spotify_visualizer")
    logical, presentation = Logical(), Presentation()
    apply_logical_vis_mode_kwargs(logical, defaults)
    apply_presentation_vis_mode_kwargs(presentation, defaults)
    logical.presentation_config_host = presentation
    logical._heartbeat_intensity = 0.0  # generated by the frame runtime, outside the settings contract
    logical.writes.clear()
    presentation.writes.clear()
    values = {"spectrum_render_mode": "segment", "spectrum_unique_colors": False,
              "spectrum_rainbow_fill": False, "spectrum_rainbow_border": True,
              "spectrum_rainbow_ghost": True, "spectrum_glow_enabled": True,
              "spectrum_glow_color": [13, 47, 82, 123], "spectrum_glow_intensity": 1.27,
              "spectrum_border_radius": 19.0, "spectrum_ghosting_enabled": True,
              "spectrum_ghost_alpha": 0.37, "spectrum_ghost_decay": 0.46,
              "spectrum_wave_amplitude": 0.63, "spectrum_profile_floor": 0.21, "spectrum_drop_speed": 2.14}
    projected = resolve_mode_source_config("spectrum", values)
    apply_logical_vis_mode_kwargs(logical, projected)
    apply_presentation_vis_mode_kwargs(presentation, projected)
    spec = require_mode_settings("spectrum")
    for control in spec.source_controls():
        assert not hasattr(logical, f"_{control.key}")
        assert not hasattr(presentation, f"_{control.key}")
    for control in spec.logical_controls():
        assert not hasattr(presentation, control_runtime_attr(control))
        assert logical.writes[control_runtime_attr(control)] == 1
    for control in spec.presentation_controls():
        assert not hasattr(logical, control_runtime_attr(control))
        assert presentation.writes[control_runtime_attr(control)] == 1

    calls = {}
    engine = SimpleNamespace(**{
        name: (lambda value, key=name: calls.setdefault(key, []).append(value))
        for name in ("set_spectrum_shaping_enabled", "set_spectrum_mirrored", "set_spectrum_shape_nodes",
                     "set_notch_positions", "set_spectrum_shape_config", "set_drop_speed")
    })
    assert apply_engine_vis_mode_kwargs(engine, projected)
    assert all(len(value) == 1 for value in calls.values())
    shape = calls["set_spectrum_shape_config"][0]
    assert shape.wave_amplitude == 0.63 and shape.profile_floor == 0.21
    assert calls["set_drop_speed"] == [2.14]
    extra = {}
    _populate_shared_visualizer_extras(extra, logical)
    assert extra["rainbow_per_bar"] is False
    for key in ("spectrum_rainbow_fill", "spectrum_rainbow_border", "spectrum_rainbow_ghost",
                "spectrum_glow_enabled", "spectrum_glow_intensity", "spectrum_glow_color",
                "spectrum_ghosting_enabled", "spectrum_ghost_alpha", "spectrum_ghost_decay"):
        assert list(extra[key]) == values[key] if isinstance(values[key], list) else extra[key] == values[key], key
    style = _common_style(logical)
    assert style["single_piece"] is False and style["border_radius"] == 19.0
    model = SpotifyVisualizerSettings.from_mapping(values, apply_preset_overlay=False)
    assert model.spectrum_border_radius == 19.0
    assert spec.control("spectrum_border_radius").high == 12.0
    assert spec.control("spectrum_border_radius").admit(100.0, 0.0) == 20.0
