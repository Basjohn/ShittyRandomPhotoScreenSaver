class SceneTargets
{
public:
    struct Target
    {
        TargetDeclaration decl;
        QSize content;        // the needed size (the surface's or the declared)
        QSize allocation;
        int samples = 1;      // effective (clamped)
        RhiOwned<QRhiTexture> colour[kMaxTargetColour];
        RhiOwned<QRhiTexture> resolve[kMaxTargetColour]; // QRhi's average, or a nearest attachment's R32F
        RhiOwned<QRhiTexture> depth;
        RhiOwned<QRhiTexture> depthNearest;              // the depth's nearest resolve (R32F window depth)
        RhiOwned<QRhiRenderPassDescriptor> renderPass;
        RhiOwned<QRhiTextureRenderTarget> renderTarget;
        // N5.2h, OpenGL only: renderTarget's attachments (resolves and depth too) without PreserveColorContents or
        // PreserveDepthStencilContents, so a pass begun on it clears every attachment to the pass's colour and the
        // depth to 1 (glClear), as the clearing draw did, without the draw's fragments; made and created beside
        // renderTarget when the declaration is pass-clearable (scenePassClearColour), null otherwise. Compatible
        // with renderPass's (OpenGL's descriptors are; the load is the only difference).
        RhiOwned<QRhiRenderPassDescriptor> clearingRenderPass;
        RhiOwned<QRhiTextureRenderTarget> clearingTarget;
        QColor clearingColour;                // the colour a pass begun on clearingTarget clears to
        // The nearest resolves' render targets (slot: a colour attachment, or kNearestDepthSlot).
        RhiOwned<QRhiRenderPassDescriptor> nearestRenderPass[kNearestSlots];
        RhiOwned<QRhiTextureRenderTarget> nearestTarget[kNearestSlots];
        RhiOwned<QRhiTexture> captureColour;
        RhiOwned<QRhiTexture> captureDepth;
        RhiOwned<QRhiRenderPassDescriptor> captureRenderPass;
        RhiOwned<QRhiTextureRenderTarget> captureTarget;
        int stepsDone = 0;
        int stepsTotal = 0;
        bool newLayout = true; // the next steps make new objects (else re-create the same at the new size)
        qint64 bytes = 0;
        int textures = 0;
        quint64 generation = 0; // a new allocation
        QString lastReason;
        // N3.4 (D17 point 2): a transparency target's borrowed textures (the owner's, not owned), set at its render
        // target's step; and (point 3) a transparency target not admitted on this device: no object, its passes drawn
        // into the owner.
        QRhiTexture *borrowedColour[kMaxTargetColour] = {};
        QRhiTexture *borrowedDepth = nullptr;
        bool dormant = false;
        // ABI 33: a self-mipped target's chain bindings (per attachment, level L >= 1: level L - 1 loaded, L stored),
        // made at the first chain after an allocation (`chainGeneration` the allocation they were made for). ABI 35:
        // the core's one kernel owner (mip_chain.h).
        MipChain chain[kMaxTargetColour];
        quint64 chainGeneration = 0;
        int chainBindings() const;
        // ABI 42 (N5.6): a cube target's objects. `colour[0]` is the cube itself (CubeMap | MipMapped | RenderTarget |
        // UsedAsTransferSource), `depth` the faces' shared D32F; `renderTarget` and `renderPass` are face 0's (the
        // passes' pipelines are built over its descriptor, compatible with every face's), `faceTarget[f]` face f's
        // (level 0, setLayer(f)). The prefilter's stage cube of each level L >= 1 (one level, `stage[L]`) and its face
        // render targets (`stageTarget[L][f]`, one descriptor a level: `stagePass[L]`).
        RhiOwned<QRhiTextureRenderTarget> faceTarget[kCubeFaces];
        RhiOwned<QRhiTexture> stage[kMaxCubeLevels];
        RhiOwned<QRhiRenderPassDescriptor> stagePass[kMaxCubeLevels];
        RhiOwned<QRhiTextureRenderTarget> stageTarget[kMaxCubeLevels][kCubeFaces];
        int cubeLevels = 0;
        // The render target a run on face `face` draws into (face 0 is the content's renderTarget).
        QRhiTextureRenderTarget *faceRenderTarget(int face) const;

        bool ready() const { return dormant || (stepsDone >= stepsTotal && renderTarget); }
        // The texture a sampler reads for this attachment: the resolve when multisampled.
        QRhiTexture *readable(int colourIndex) const;
        QRhiTexture *readableDepth() const;
        // N3.4: the texture an attachment draws into (its own, or the owner's it borrows), and the depth.
        QRhiTexture *colourTexture(int colourIndex) const;
        QRhiTexture *depthTexture() const { return depth ? depth.get() : borrowedDepth; }
        // A nearest resolve slot in use (multisampled, and read): its multisampled source and its R32F destination.
        bool nearestActive(int slot) const;
        QRhiTexture *nearestSource(int slot) const;
        QRhiTexture *nearestDest(int slot) const;
    };

    SceneTargets();
    ~SceneTargets();
    SceneTargets(const SceneTargets &) = delete;
    SceneTargets &operator=(const SceneTargets &) = delete;

    // Render thread, at the record: the program's targets and the surface's pixels. Decides each target's allocation
    // (D14 point 2) and effective samples; makes nothing yet (allocateStep does). `relayout`: a render-pass descriptor
    // will go, so the caller releases the pipelines built over it first. False with the reason for a target that cannot
    // exist on this device (a size past the device's limit).
    bool sync(QRhi *rhi, const QList<TargetDeclaration> &declarations, const QSize &surface, bool *relayout,
              QString *error);
    // N3.4 (D17 point 3), render thread, before sync: the transparency targets not admitted on this device (bit i: target
    // i), with each one's reason for the state. A dormant target holds no object; a change is a layout edge.
    void setDormant(quint32 mask, const QStringList &reasons);
    quint32 dormantMask() const { return m_dormant; }
    // Render thread: one step of what sync left (one colour attachment with its resolve, the depth with its resolve, the
    // render target, the capture). True once nothing is left (`done`), false with the reason when an object could not be
    // made: the caller then releases the pipelines built over the targets' descriptors and then the targets (release()),
    // in that order (audit 2, L5: a same-layout resize keeps its descriptor and its pipelines until then).
    bool allocateStep(bool *done, QString *error);
    bool complete() const;

    int count() const { return m_count; }
    int indexOf(const QByteArray &name) const;
    Target *target(int index) { return index >= 0 && index < m_count ? m_targets[index].get() : nullptr; }
    const Target *target(int index) const { return index >= 0 && index < m_count ? m_targets[index].get() : nullptr; }
    // The texture a sampler named "<target>.<attachment>" reads (an attachment, "depth", "capture_colour",
    // "capture_depth"); null when there is none.
    QRhiTexture *sampledTexture(const QByteArray &name) const;
    // The textures a run on target `index` loads (its colour attachments; rule C primes them), into `out` (room for
    // kMaxTargetColour); returns how many. Nothing allocated (audit 2, M5).
    int loadedColour(int index, QRhiTexture **out) const;
    // The resolve textures a run on target `index` writes (QRhi's average of a read multisampled attachment; audit 2,
    // H1: primed before every run), into `out` (room for kMaxTargetColour); returns how many.
    int averageResolves(int index, QRhiTexture **out) const;
    // ABI 33, render thread, after a run of passes on target `index` (outside any pass): a self-mipped target's chains
    // of the attachments a sampler reads with mips, one compute pass of the box kernel a level; nothing for any other
    // target. Returns the chains made; false in `ok` (with `error`) when the kernel or a binding could not be made, or
    // the device has no compute (the content's failure).
    int generateSelfMips(QRhi *rhi, QRhiCommandBuffer *cb, int index, bool *ok, QString *error);

    quint64 layoutGeneration() const { return m_layoutGeneration; }
    quint64 objectGeneration() const { return m_objectGeneration; }
    int liveObjects() const;

    // Render thread: every object goes (the content's release).
    void release();

    // Render thread, after the record's passes: a readback of every readable texture (harness only).
    std::shared_ptr<SceneReadback> startReadback(QRhiCommandBuffer *cb);

    // The targets' state as values (render thread; the caller hands it to the source's report), and whether it changed
    // since the last call that returned true (audit 2, M5: the report is written only then, never per record).
    SceneTargetsState state(QRhi *rhi) const;
    bool takeStateChange();

private:
    void releaseTarget(Target &t);
    bool step(Target &t, int index, QString *error);
    // ABI 33: the box kernel (ABI 35: the core's one owner of it, mip_chain.h).
    static void releaseChain(Target &t);
    MipChainKernel m_chainKernel;

    QRhi *m_rhi = nullptr;
    std::unique_ptr<Target> m_targets[kMaxSceneTargets];
    int m_count = 0;
    quint64 m_layoutGeneration = 0;
    quint64 m_objectGeneration = 0;
    qint64 m_allocations = 0;
    qint64 m_steps = 0;
    QList<int> m_supported;
    const QRhi *m_supportedRhi = nullptr;     // m_supported is this QRhi's ...
    quint64 m_supportedControl = 0;           // ... under this generation of the clamp's control (M5: not per record)
    quint64 m_stateVersion = 0;               // a change of what state() reports
    quint64 m_stateNoted = 0;
    quint32 m_dormant = 0;                    // N3.4: the transparency targets not admitted (setDormant)
    QStringList m_fallbacks;
};

