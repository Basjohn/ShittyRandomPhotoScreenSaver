// ABI 37 (N4.i): R8, the motion trails' ghost buffer (one unorm channel, MAX-blended: Python's GL_R8).
enum class TargetFormat { RGBA8 = 0, RGBA16F = 1, R16F = 2, R32F = 3, R8 = 4 };
