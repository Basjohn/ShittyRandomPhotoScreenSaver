// Scene targets (Current_Plan.md item 8b, N3.1; decision D14 in Docs/Future_Work/Native_Core_P3_Decisions.md): the
// intermediate targets a generic mode's or a fullscreen pass's passes draw into before what reaches the surface, as
// data in its program (mode_content.h). The Python oracle is rendering/quick/scene3d/target.py SceneTarget (colour,
// depth, the HDR intermediate, the mid-scope background() capture) and Bubble's ambient target
// (rendering/quick/visualizer/implementations/bubble_ambient_gl.py: a coverage and a light attachment).
//
// A target is declared by its program: a name; a size (the surface's device pixels, or explicit pixels from Python); 1 to
// 4 named colour attachments (RGBA8, RGBA16F, R16F, R32F; D14 point 4: the HDR intermediate is RGBA16F); a depth (none,
// or one D32F texture: D14 point 5, choice C); a requested sample count (D14 point 7: rendering/gl_programs/scene3d.py
// owns the request, the core's clamp here is the only place it meets a device).
//
// Allocation per size (D14 point 2, choice A): 64 px buckets, each axis on its own (audit 2, L1); an axis grows at once
// whenever the needed size passes it, and shrinks only when the needed size falls two or more buckets below it, decided
// at the size edge (the record that sees a new surface or explicit size), never by a timer. An allocation is made one
// attachment per step (allocateStep: N3.6 schedules the steps as warm-up units; until then the record runs them all).
// The content sits at image rows [H-h, H) and columns [0, w) of the allocation (the Python renderer's GL bottom-left), so
// a read past the content's edge reads what Python's reads; contentViewport gives QRhi's viewport per backend.
//
// Resize (D14 point 3): a new allocation of the same layout re-creates the same QRhi objects at the new size (the
// render-pass descriptor stays: the pipelines are kept, the passes' bindings are made again over the new objects:
// objectGeneration); a new layout (formats, attachments, depth, samples) makes new objects and a new render-pass
// descriptor (layoutGeneration: the pipelines are built again; the content releases them before the old descriptor goes).
//
// Multisampled targets resolve first (D14 point 8): every attachment a sampler or the capture reads gets a resolve
// texture (QRhi's average). A read depth, and an R32F attachment declared "resolve": "nearest", get the core's own
// per-sample nearest resolve instead (D14 point 10, the lead's decision after build round 2: QRhi's depth resolve gave
// wrong values on both backends and dropped the multisampled depth): a fullscreen pass (shaders/scene_nearest.frag)
// reads every sample of the multisampled texture and writes the minimum into a single-sampled R32F texture, which the
// samplers and the capture read; nothing sets a depth resolve texture, so the multisampled depth is stored and loaded
// across a capture. It runs after a run of passes on the target only when a later pass reads it (or a readback asks).
// QRhi's average resolves are ordered after their last store before every run (targets.h primeResolvesForPass; audit 2,
// H1: a resolve attachment's render pass transitions it from UNDEFINED with no external dependency).
// Every target keeps its contents (targets.h rule B, depth too) and is cleared by a draw.
//
// N3.4 (D17; post_stages.h): a transparency target owns its accumulation and coverage and borrows its owner's depth
// and named attachments (the same textures, in a render target of its own; its clearing draw writes its own two
// only); it is its owner's allocation and samples and is made again whenever the owner is. A transparency target the
// device gate does not admit is dormant (setDormant): it holds nothing and its passes draw into the owner. A mipped
// target (the defocus layer) holds every level of its attachments, generated by the defocus step, and its readback
// reads every level ("<target>.<attachment>@<level>" past 0). Its allocation follows the bucket rule (D17 choice H), so
// levels 1 to 6 always halve an even size; QRhi's generateMips makes a level from an odd size differently per backend
// (the driver's filter on OpenGL, a linear blit on Vulkan), which is why the defocus step's read level is capped
// (post_stages.h defocusReadLevelCap).
// ABI 33 (N5.4): a mipped target no defocus step reads is drawn by passes like any target (a depth and an explicit
// size allowed, single-sampled), its chains generated after each run on it (generateSelfMips), and samplers read its
// levels. With "allocation": "exact" its allocation is the content's size (no bucket: Waveform's reflection reads its
// coarse levels and its 1x1 level as the scene's mean, which a bucket's empty texels would dilute); its odd levels are
// then the backends' own (the driver's box on OpenGL, Python's call; a linear blit on Vulkan), judged by the proof.
// ABI 42 (N5.6, the scene probe; N4.d's Extruded Bubble half, the lead's decision of 15 Nov): a cube target ("cube":
// true) is rendering/quick/scene3d/probe.py's SceneProbe: one RGBA16F cube of an explicit square size with its full mip
// chain, its own clear, and one D32F depth (2D, the face's size) shared by the six faces and cleared per face. Each face
// is a render target of its own over the cube's level 0 (QRhiColorAttachment::setLayer), drawn by the passes that
// declare that face (mode_content.h); the faces hold OpenGL's cube-map convention (each face's bottom row at memory
// row 0, the rows Python's glFramebufferTextureLayer draws), so the shells' lookups read the same texel on every
// backend. The chain is the core's prefilter (cube_prefilter.h: probe.py's 32 Gaussian taps over a cone, never
// generateMips, no geometry-shader gl_Layer): level L of each face is drawn into a per-level stage cube from the cube's
// level L - 1, then copied into the cube's level L (QRhi tracks a texture whole: one texture is never read and written
// in one pass). A sampler reads the cube as a samplerCube with its mips.
//
// Render thread only, but the counts (any thread) and the readback's results (taken by the GUI thread through
// SceneReadback's own lock).
