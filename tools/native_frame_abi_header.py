"""The frame packet ABI and the native frame schemas as one C++ header for the native core's packet reader (N2.3).

The Python modules stay the single source: ``core/visualizer_engine/packet_abi.py`` (the mapping's header and slot
layout, the mode codes) and ``core/visualizer_engine/native_schema.py`` with its per-mode schemas (each record's
fields, offsets and range rules). This tool writes them into ``native/core/src/frame_abi_generated.h``, which the C++
reader (``native/core/src/packet_reader.cpp``) compiles; ``--check`` fails while the committed header differs from what
the Python modules say (``tests/test_native_packet_reader_sources.py`` runs it), so the two readers cannot drift.

    python tools/native_frame_abi_header.py [--check] [--repo .]
"""
from __future__ import annotations

import argparse
import os
import re
import struct
import sys
from pathlib import Path

HEADER_RELATIVE = Path("native") / "core" / "src" / "frame_abi_generated.h"
_KIND = {"u32": "FieldKind::U32", "f64": "FieldKind::F64", "f64x4": "FieldKind::F64x4"}
_CHECK = {None: "FieldCheck::None", "at_most": "FieldCheck::AtMost", "boolean": "FieldCheck::Boolean",
          "enum": "FieldCheck::Enum"}


_SLOT_FIELDS = ("sequence_begin", "payload_bytes", "payload_schema", "logical_timestamp", "source_timestamp", "flags",
                "protected_edge_mask", "runtime_generation", "engine_generation", "activation_id", "mode_code",
                "publish_ns")
_HEADER_FIELDS = ("magic", "abi_version", "header_bytes", "runtime_generation", "engine_generation", "activation_id",
                  "slot_count", "slot_bytes", "mode_code", "latest_sequence", "consumed_sequence")


def _offsets(fmt: str, names: tuple[str, ...]) -> dict[str, int]:
    """Each field's offset in a little-endian ``struct`` format, read from ``packet_abi``'s own format (never typed
    twice)."""
    codes = re.findall(r"\d*[a-zA-Z?]", fmt.lstrip("<"))
    if len(codes) != len(names):
        raise RuntimeError(f"packet_abi's format {fmt!r} no longer has the {len(names)} fields {names}")
    return {name: struct.calcsize("<" + "".join(codes[:index])) for index, name in enumerate(names)}


def _slot_offsets() -> dict[str, int]:
    from core.visualizer_engine import packet_abi

    return _offsets(packet_abi._SLOT_HEAD.format, _SLOT_FIELDS)


def _header_offsets() -> dict[str, int]:
    from core.visualizer_engine import packet_abi

    offsets = _offsets(packet_abi._HEADER.format, _HEADER_FIELDS)
    # The module's own named offsets agree with its header format.
    named = {"runtime_generation": packet_abi._IDENTITY_OFFSET, "mode_code": packet_abi._MODE_CODE_OFFSET,
             "latest_sequence": packet_abi._LATEST_OFFSET, "consumed_sequence": packet_abi._CONSUMED_OFFSET}
    for name, offset in named.items():
        if offsets[name] != offset:
            raise RuntimeError(f"packet_abi's {name} offset {offset} disagrees with its header format")
    return offsets


def _camel(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def render() -> str:
    from core.visualizer_engine import native_schema, packet_abi
    from core.visualizer_engine.frame_codec import CODEC_SCHEMA

    slot = _slot_offsets()
    lines = [
        "// GENERATED by tools/native_frame_abi_header.py from core/visualizer_engine/packet_abi.py and",
        "// core/visualizer_engine/native_schema.py (with its per-mode schemas). Do not edit: change the Python modules and",
        "// run the tool; tests/test_native_packet_reader_sources.py fails while this file differs from what they say.",
        "#pragma once",
        "",
        "#include <QtCore/QtGlobal>",
        "",
        "namespace srpss_core::frame_abi {",
        "",
        "// The mapping (packet_abi.py's module docstring has the layout and the seqlock order).",
        f'constexpr char kMagic[5] = "{packet_abi.MAGIC.decode("ascii")}";',
        f"constexpr quint16 kAbiVersion = {packet_abi.ABI_VERSION};",
        f"constexpr quint32 kHeaderBytes = {packet_abi.HEADER_BYTES};",
        f"constexpr quint32 kSlotCount = {packet_abi.SLOT_COUNT};",
        f"constexpr quint32 kSlotPayloadOffset = {packet_abi.SLOT_PAYLOAD_OFFSET};",
        f"constexpr quint32 kSlotOverhead = {packet_abi.SLOT_OVERHEAD};",
        f"constexpr quint64 kFirstSequence = {packet_abi.FIRST_SEQUENCE};",
        f'constexpr char kMappingPrefix[] = "{packet_abi.FRAME_MAPPING_PREFIX}";',
        "",
        "// Header offsets.",
    ]
    for name, offset in _header_offsets().items():
        lines.append(f"constexpr quint32 kHeader{_camel(name)} = {offset};")
    lines += [
        f"constexpr quint32 kHeaderRejectedPayload = {packet_abi._REJECTED_PAYLOAD_OFFSET};",
        "",
        "// Slot head offsets (the slot's sequence_end is the slot's last 8 bytes).",
    ]
    for name, offset in slot.items():
        lines.append(f"constexpr quint32 kSlot{_camel(name)} = {offset};")
    lines += [
        "",
        "// Slot flags.",
        f"constexpr quint32 kFlagChanged = {packet_abi.FLAG_CHANGED};",
        f"constexpr quint32 kFlagPresentFrame = {packet_abi.FLAG_PRESENT_FRAME};",
        f"constexpr quint32 kFlagModeRevealReady = {packet_abi.FLAG_MODE_REVEAL_READY};",
        f"constexpr quint32 kFlagPlaying = {packet_abi.FLAG_PLAYING};",
        "",
        "// The payload_schema namespace (native_schema.py, transport rule 4).",
        f"constexpr quint32 kCodecSchema = {CODEC_SCHEMA};",
        f"constexpr quint32 kNativeBase = 0x{native_schema.NATIVE_BASE:X};",
        f"constexpr quint32 kEnumOutside = 0x{native_schema.ENUM_OUTSIDE:X}u;",
        "",
        "struct ModeCode",
        "{",
        "    const char *modeId;",
        "    quint32 code;",
        "};",
        "",
        "// MODE_CODES: append-only, one stable number per canonical mode id.",
        "constexpr ModeCode kModeCodes[] = {",
    ]
    for mode_id, code in sorted(packet_abi.MODE_CODES.items(), key=lambda item: item[1]):
        lines.append(f'    {{ "{mode_id}", {code} }},')
    lines += [
        "};",
        "",
        "enum class FieldKind : quint8 { U32, F64, F64x4 };",
        "enum class FieldCheck : quint8 { None, AtMost, Boolean, Enum };",
        "",
        "struct Field",
        "{",
        "    const char *name;",
        "    FieldKind kind;",
        "    quint32 count;  // 1, or the array's length",
        "    quint32 offset; // in the record",
        "    FieldCheck check;",
        "    quint32 limit;  // AtMost: the largest value; Enum: the table's length (kEnumOutside also admitted)",
        "};",
        "",
        "struct Schema",
        "{",
        "    const char *modeId;",
        "    quint32 modeCode;",
        "    quint32 version;",
        "    quint32 schemaId;",
        "    quint32 recordBytes;",
        "    const char *fingerprint; // NativeLayout.fingerprint(): the Python face compares it at reader creation",
        "    const Field *fields;     // the decoded record's fields in the reference decoder's order",
        "    quint32 fieldCount;",
        "    const quint32 *checkOrder; // indexes into fields: the range rules in the order the reference applies them",
        "    quint32 checkCount;",
        "};",
        "",
    ]
    schemas = sorted(native_schema.native_schemas().values(), key=lambda schema: schema.schema_id)
    table_rows = []
    for schema in schemas:
        symbol = _camel(schema.mode_id) + f"V{schema.version}"
        checks = {name: (kind, limit) for name, kind, limit in schema.checks}
        order = [name for name, _kind, _limit in schema.checks]
        if not schema.fields:
            raise RuntimeError(f"schema {schema.schema_id:#x} names no fields")
        lines.append(f"constexpr Field k{symbol}Fields[] = {{")
        for name in schema.fields:
            field = schema.layout.field(name)
            kind, limit = checks.get(name, (None, 0))
            lines.append(f'    {{ "{name}", {_KIND[field.kind]}, {field.count}, {field.offset}, {_CHECK[kind]}, '
                         f'{limit}u }},')
        lines.append("};")
        indexes = ", ".join(str(schema.fields.index(name)) for name in order) or "0"
        lines.append(f"constexpr quint32 k{symbol}CheckOrder[] = {{ {indexes} }};")
        lines.append("")
        table_rows.append(
            f'    {{ "{schema.mode_id}", {schema.mode_code}, {schema.version}, 0x{schema.schema_id:X}u, '
            f'{schema.layout.size}, "{schema.layout.fingerprint()}", k{symbol}Fields, '
            f'quint32(sizeof(k{symbol}Fields) / sizeof(Field)), k{symbol}CheckOrder, {len(order)} }},')
    lines.append("// Every native schema this build knows (native_schema.native_schemas()).")
    lines.append("constexpr Schema kSchemas[] = {")
    lines += table_rows
    lines += ["};", "", "} // namespace srpss_core::frame_abi", ""]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--repo", default=".", help="the repository root (default: the current directory)")
    parser.add_argument("--check", action="store_true", help="fail while the committed header is stale")
    args = parser.parse_args(argv)
    root = os.path.abspath(args.repo)
    sys.path.insert(0, root)
    from tools.artifact_paths import repository_root

    target = Path(repository_root(root)) / HEADER_RELATIVE
    text = render()
    current = target.read_text(encoding="utf-8") if target.is_file() else None
    if args.check:
        if current != text:
            print(f"{target} is stale: run python tools/native_frame_abi_header.py")
            return 1
        print(f"{target} is current")
        return 0
    if current != text:
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target}")
    else:
        print(f"{target} unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
